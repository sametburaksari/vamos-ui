#!/usr/bin/env node
/**
 * Writes src/project/recipes/data/index.ts: one static import per recipe JSON file, so bundlers
 * and the pure library entry carry every recipe. Run after adding or removing a recipe:
 *   node packages/cli/scripts/gen-recipes.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/project/recipes/data");
export function recipeIndex(files) {
  const ident = (f) => "r_" + f.replace(/\.json$/, "").replace(/[^a-z0-9]+/gi, "_");
  return [
    "// AUTO-GENERATED by packages/cli/scripts/gen-recipes.mjs — do not edit by hand.",
    ...files.map((f) => `import ${ident(f)} from "./${f}";`),
    "",
    `export const RECIPE_DATA = [${files.map(ident).join(", ")}];`,
    "",
  ].join("\n");
}
export const recipeFiles = () => fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(path.join(dir, "index.ts"), recipeIndex(recipeFiles()));
  console.log(`recipes: ${recipeFiles().length}`);
}
