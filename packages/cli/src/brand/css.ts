/** brandCss: vamos.brand.json → brand.css. Pure and deterministic (snapshot-safe). */
import { generateAccent, type AccentPalette } from "./accent";
import { formatOklch, parseColor } from "./color";
import { displayTokens, FONT_ROLE_VARS, isGenericFamily, roleStack } from "./fonts";
import { BRAND_AXIS_VALUE, type Brand } from "./types";

export const BRAND_CSS_FILE = "brand.css";
export const BRAND_CSS_HEADER = "/* vamos-ui brand";

const RADIUS: Record<"sharp" | "round", { comfortable: string; compact: string }> = {
  sharp: { comfortable: "6px", compact: "4px" },
  round: { comfortable: "20px", compact: "14px" },
};

export interface BrandCssOptions {
  /** Precomputed palette (saves recomputing when the caller already has it). */
  palette?: AccentPalette;
}

/** Does the brand define any fonts (and so a `data-font="brand"` block)? */
export const brandHasFonts = (brand: Pick<Brand, "fonts">) =>
  (["display", "body", "mono"] as const).some((r) => !!brand.fonts?.[r] && !isGenericFamily(brand.fonts[r]!));

/**
 * The stylesheet for a brand: `[data-accent="brand"]` with the four accent variables (plus a
 * dark-mode fill when needed, radius and backdrop tint) and `[data-font="brand"]` with the
 * font variables. Import it after the kit's styles.css. Throws a TypeError on invalid colours.
 */
export function brandCss(brand: Brand, options: BrandCssOptions = {}): string {
  const palette = options.palette ?? generateAccent(brand.colors.accent, { dark: brand.colors.accentDark });
  const sel = `[data-accent="${BRAND_AXIS_VALUE}"]`;
  const out: string[] = [];
  out.push(`${BRAND_CSS_HEADER}: ${brand.name.replace(/\*\//g, "")}`);
  out.push(" * Generated by `vamos-ui brand apply` from vamos.brand.json. Edit the JSON and re-run");
  out.push(" * instead of editing this file. Use: <html data-accent=\"brand\"" + (brandHasFonts(brand) ? ' data-font="brand"' : "") + ">");
  out.push(" */");
  out.push("");
  out.push(`${sel} {`);
  out.push(`  --accent-base: ${palette.base}; /* source ${palette.source.replace(/\*\//g, "")} */`);
  out.push(`  --accent-fg: ${palette.fg}; /* ${palette.contrast.fgOnBase}:1 on the fill */`);
  out.push(`  --accent-ink-light: ${palette.inkLight}; /* ${palette.contrast.inkLightOnLight}:1 on light surfaces */`);
  out.push(`  --accent-ink-dark: ${palette.inkDark}; /* ${palette.contrast.inkDarkOnDark}:1 on dark surfaces */`);

  const radius = brand.theme?.radius;
  if (radius === "sharp" || radius === "round") out.push(`  --radius: ${RADIUS[radius].comfortable};`);

  const tint = brand.colors.neutralTint ? parseColor(brand.colors.neutralTint) : null;
  if (brand.colors.neutralTint && !tint) throw new TypeError(`"${brand.colors.neutralTint}" (neutralTint) is not a colour.`);
  const scene = tint ? { light: formatOklch({ l: 0.95, c: Math.min(0.014, Math.max(0.006, tint.c * 0.12)), h: tint.h, alpha: 1 }), dark: formatOklch({ l: 0.165, c: Math.min(0.01, Math.max(0.004, tint.c * 0.08)), h: tint.h, alpha: 1 }) } : null;
  if (scene) out.push(`  --scene: ${scene.light};`);
  out.push("}");

  if (radius === "sharp" || radius === "round") {
    out.push(`${sel}[data-density="compact"],`);
    out.push(`${sel} [data-density="compact"] {`);
    out.push(`  --radius: ${RADIUS[radius].compact};`);
    out.push("}");
  }

  if (palette.dark || scene) {
    out.push(`.dark${sel},`);
    out.push(`.dark ${sel} {`);
    if (palette.dark) {
      out.push(`  --accent-base: ${palette.dark.base};`);
      out.push(`  --accent-fg: ${palette.dark.fg}; /* ${palette.contrast.darkFgOnBase}:1 on the dark-mode fill */`);
    }
    if (scene) out.push(`  --scene: ${scene.dark};`);
    out.push("}");
    // A light section inside a dark page gets the light values back.
    out.push(`.dark .light${sel},`);
    out.push(`.dark .light ${sel} {`);
    if (palette.dark) {
      out.push(`  --accent-base: ${palette.base};`);
      out.push(`  --accent-fg: ${palette.fg};`);
    }
    if (scene) out.push(`  --scene: ${scene.light};`);
    out.push("}");
  }

  if (brandHasFonts(brand)) {
    out.push("");
    out.push(`[data-font="${BRAND_AXIS_VALUE}"] {`);
    for (const role of ["body", "display", "mono"] as const) {
      const family = brand.fonts[role];
      if (!family || isGenericFamily(family)) continue;
      out.push(`  ${FONT_ROLE_VARS[role].token}: ${roleStack(role, family)};`);
    }
    const tokens = displayTokens(brand.fonts.display);
    if (tokens) {
      out.push(`  --display-weight: ${tokens.weight};`);
      out.push(`  --display-tracking: ${tokens.tracking};`);
      out.push(`  --display-em: ${tokens.em};`);
      out.push(`  --display-scale: ${tokens.scale};`);
    }
    out.push("}");
  }
  return out.join("\n") + "\n";
}

/** Reads the four accent variables (and the dark override) back out of a brand.css. */
export function readBrandCssVars(css: string): { light: Record<string, string>; dark: Record<string, string> } {
  const light: Record<string, string> = {};
  const dark: Record<string, string> = {};
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  for (const m of clean.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selector = m[1]!.trim();
    if (!/\[data-accent=["']?brand["']?\]/.test(selector) || /\.light/.test(selector)) continue;
    const target = /\.dark/.test(selector) ? dark : light;
    for (const d of m[2]!.matchAll(/(--accent-[\w-]+)\s*:\s*([^;]+);?/g)) target[d[1]!] = d[2]!.trim();
  }
  return { light, dark };
}
