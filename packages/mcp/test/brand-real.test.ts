import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { brandIssues } from "../src/brand.js";
import { loadBrandLib } from "../src/brand-lib.js";
import { applyDesignSystem, getBrand, importDesignSystem, proposeAccent, updateDesign } from "../src/design-tools.js";

// Runs against the real "vamos-ui/brand" once packages/cli has it; skipped until then.
const lib = await loadBrandLib();

describe.skipIf(!lib)("with the real vamos-ui/brand", () => {
  it("propose_accent returns contrast-safe variables for a mid-tone brand colour", async () => {
    const res = await proposeAccent({ colour: "#0f766e" });
    const accent = res.data.accent as { base: string; contrast: { fgOnBase: number; inkLightOnLight: number; inkDarkOnDark: number } };
    expect(accent.base).toBeTruthy();
    expect(accent.contrast.fgOnBase).toBeGreaterThanOrEqual(4.5);
    expect(accent.contrast.inkLightOnLight).toBeGreaterThanOrEqual(4.5);
    expect(accent.contrast.inkDarkOnDark).toBeGreaterThanOrEqual(4.5);
    expect(res.text).toMatch(/\[data-accent="brand"\]/);
  });

  it("reports a missing voice once, even with the library's own check", () => {
    const raw = { name: "Kuzey", colors: { accent: "#0f766e" }, voice: { examples: [{ do: "Track every pallet." }] }, assets: [{ path: "https://kuzey.example/logo.svg", use: "Logo" }] };
    const issues = brandIssues(raw, undefined, lib);
    expect(issues.filter((i) => i.path === "voice")).toHaveLength(1);
    expect(issues.find((i) => i.path === "voice")!.message).toMatch(/examples but no tone or rules/);
  });

  it("update_design previews the automatic fixes `vamos-ui update --fix` makes", async () => {
    const root = mkdtempSync(path.join(tmpdir(), "vamos-mcp-fix-"));
    try {
      mkdirSync(path.join(root, "src/components"), { recursive: true });
      writeFileSync(path.join(root, "vamos.json"), JSON.stringify({ uiDir: "src/components/vamos", css: "src/app/globals.css" }));
      writeFileSync(path.join(root, "vamos.brand.json"), JSON.stringify({ name: "Kuzey", colors: { accent: "#2563eb" } }));
      writeFileSync(path.join(root, "src/components/promo.tsx"), `export const P = () => <div className="bg-blue-600 text-white dark:bg-blue-500 z-[999]">Go</div>;\n`);
      const res = await updateDesign({ projectDir: root });
      const fixes = res.data.fixes as { changes: number; files: { file: string; remaining: number }[]; mappings: { from: string; to: string }[] };
      expect(fixes.files).toEqual([{ file: "src/components/promo.tsx", changes: 3, remaining: 1 }]);
      expect(fixes.mappings).toEqual(expect.arrayContaining([{ from: "bg-blue-600", to: "bg-accent", count: 1 }]));
      expect(res.text).toContain("npx vamos-ui update --fix");
      expect(res.text).not.toMatch(/run `npx vamos-ui update` \(edited kit files/);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("import_design_system reads theme-color and Google Fonts from HTML", async () => {
    const html = `<!doctype html><html><head><title>Kuzey Lojistik</title>
      <meta name="theme-color" content="#0f766e">
      <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Hanken+Grotesk:wght@400;600&display=swap">
      <style>body{font-family:"Hanken Grotesk",sans-serif}.btn{background:#0f766e;color:#fff}</style></head><body></body></html>`;
    const res = await importDesignSystem({ html, base_url: "https://kuzey.example/" });
    const brand = res.data.brand as { colors: { accent?: string }; fonts?: { body?: string; display?: string } };
    expect(brand.colors.accent).toBeTruthy();
    expect(JSON.stringify(brand.fonts ?? {})).toMatch(/Hanken Grotesk/);
  });

  it("apply_design_system plans a brand.css generated by the library", async () => {
    const root = mkdtempSync(path.join(tmpdir(), "vamos-mcp-real-"));
    try {
      const files: Record<string, string> = {
        "vamos.json": JSON.stringify({ uiDir: "src/components/vamos", css: "src/app/globals.css" }),
        "src/app/globals.css": '@import "tailwindcss";\n@import "../components/vamos/styles.css";\n',
        "vamos.brand.json": JSON.stringify({ name: "Kuzey", colors: { accent: "#0f766e" }, fonts: { body: "Hanken Grotesk" } }),
      };
      for (const [rel, content] of Object.entries(files)) {
        mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
        writeFileSync(path.join(root, rel), content);
      }
      const brand = await getBrand({ projectDir: root });
      expect(brand.text).toMatch(/--accent-base:/);
      const res = await applyDesignSystem({ projectDir: root });
      const css = (res.data.edits as { path: string; content: string }[]).find((e) => e.path.endsWith("brand.css"));
      expect(css?.content).toMatch(/\[data-accent="brand"\]/);
      expect(css?.content).toMatch(/--accent-ink-dark/);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
