#!/usr/bin/env node
// Regenerates the Turkish neighbourhood (mahalle) and village (köy) files, one JSON per province:
//   src/locale-data/tr/neighbourhoods/01.json … 81.json
//   src/locale-data/tr/neighbourhoods-bundled.ts (the 81 lazy imports)
//
// Input: a checkout (or download) of the `datasets/` folder of github.com/ubeydeozdmr/turkiye-api
// (MIT). Names come from TÜİK MEDAS, postal codes from PTT; district ids are the NVİ codes used in
// address-tr.json, and the script refuses to write when a district id or name disagrees with it.
//   node packages/ui/scripts/tr-neighbourhoods.mjs /path/to/turkiye-api/datasets
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TR = path.join(PKG, "src/locale-data/tr");
const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/tr-neighbourhoods.mjs <turkiye-api/datasets>");
  process.exit(1);
}
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const neighbourhoods = read("neighborhoods.json");
const villages = read("villages.json");
const municipalities = new Map(read("municipalities.json").map((m) => [m.id, m]));
const districts = new Map(read("districts.json").map((d) => [d.id, d]));
const address = JSON.parse(fs.readFileSync(path.join(TR, "address-tr.json"), "utf8"));

// Same districts, same names, or stop.
const ours = new Map(address.provinces.flatMap(([plate, , ds]) => ds.map(([code, name]) => [code, { plate, name }])));
const problems = [];
for (const [code, d] of ours) {
  const t = districts.get(code);
  if (!t) problems.push(`district ${code} ${d.name} missing in dataset`);
  else if (t.name !== d.name || t.provinceId !== d.plate) problems.push(`district ${code}: ${d.name}/${d.plate} vs ${t.name}/${t.provinceId}`);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const SOURCE =
  "github.com/ubeydeozdmr/turkiye-api datasets (dataset 2025, updated 2026-05-21): neighbourhood and village names from TÜİK MEDAS, postal codes from PTT (official codes only); district ids match address-tr.json (NVİ)";
const LICENSE = "MIT License, Copyright (c) 2022-2026 Ubeyde Emir Özdemir (dataset compilation); underlying names are official public records";
const generated = new Date().toISOString().slice(0, 10);

const byPlate = new Map();
const add = (x, row) => {
  if (!ours.has(x.districtId)) throw new Error(`unknown district ${x.districtId} for ${x.name}`);
  const p = byPlate.get(x.provinceId) ?? new Map();
  byPlate.set(x.provinceId, p);
  const list = p.get(x.districtId) ?? [];
  p.set(x.districtId, list);
  list.push(row);
};
const postal = (x) => (x.postalCodeStatus === "official" && /^\d{5}$/.test(x.postalCode ?? "") ? x.postalCode : "");
for (const x of neighbourhoods) {
  const m = municipalities.get(x.municipalityId);
  const town = m && m.type === "town" ? m.name : undefined;
  add(x, town ? [x.name, postal(x), 0, town] : [x.name, postal(x)]);
}
for (const x of villages) add(x, [x.name, postal(x), 1]);

let total = 0;
for (let plate = 1; plate <= 81; plate++) {
  const p = byPlate.get(plate);
  if (!p) throw new Error(`no data for plate ${plate}`);
  const out = {};
  for (const code of [...p.keys()].sort((a, b) => a - b)) {
    const rows = p.get(code).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
    out[code] = rows;
    total += rows.length;
  }
  const file = { source: SOURCE, license: LICENSE, generated, plate, districts: out };
  fs.writeFileSync(path.join(TR, "neighbourhoods", `${String(plate).padStart(2, "0")}.json`), JSON.stringify(file) + "\n");
}

const lines = [];
for (let plate = 1; plate <= 81; plate++) {
  const id = String(plate).padStart(2, "0");
  lines.push(`  ${plate}: () => import("./neighbourhoods/${id}.json"),`);
}
fs.writeFileSync(
  path.join(TR, "neighbourhoods-bundled.ts"),
  `// AUTO-GENERATED by scripts/tr-neighbourhoods.mjs — do not edit by hand.
/**
 * Turkish neighbourhoods and villages bundled with the package, one lazy chunk per province
 * (${total} entries in 81 files). Each province file loads on first use; nothing reaches the main
 * bundle. Import from \`@vamos-ui/react/locale-data/tr-neighbourhoods\`.
 */
import type { AddressDataSource } from "../core/types";
import { trAddress } from "./address";
import { createTrNeighbourhoodLoader, withNeighbourhoods, type TrNeighbourhoodFile } from "./neighbourhoods";

const FILES: Record<number, () => Promise<unknown>> = {
${lines.join("\n")}
};

/** Loads one province file (plate 1–81) from the package. */
export function loadTrNeighbourhoodFile(plate: number): Promise<TrNeighbourhoodFile> {
  const load = FILES[plate];
  if (!load) return Promise.reject(new RangeError(\`loadTrNeighbourhoodFile: unknown plate \${plate}\`));
  return load().then((m) => ((m as { default?: unknown }).default ?? m) as TrNeighbourhoodFile);
}

/** \`(plate, districtCode) => neighbourhoods\` over the bundled files, cached per province. */
export const trNeighbourhoods = /*#__PURE__*/ createTrNeighbourhoodLoader(loadTrNeighbourhoodFile);

/** \`trAddress\` plus bundled neighbourhoods: pass as \`sources={{ TR: trAddressWithNeighbourhoods }}\`. */
export const trAddressWithNeighbourhoods: AddressDataSource = /*#__PURE__*/ withNeighbourhoods(trAddress, trNeighbourhoods);
`,
);
console.log(`✓ ${total} neighbourhoods and villages in 81 province files`);
