type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

/** The complete dictionary shape. Every locale must provide all of it (`satisfies Messages`). */
export type Messages = Widen<typeof en>;

/**
 * A partial dictionary: any subset of `Messages`, plus namespaces the built-in dictionary
 * doesn't list yet (components bring their own English defaults). Deep-merged over the base.
 */
export type MessagesInput = { [K in keyof Messages]?: Partial<Messages[K]> } & {
  [namespace: string]: Record<string, string | undefined> | undefined;
};
