/** Labels accepted by every registry-2 block: infrastructure + these keys. */
export type Site2BlockLabels = Partial<BlockLabels & Site2Labels>;
export type Site2Key = keyof (BlockLabels & Site2Labels);
export type Site2Text = (key: Site2Key, vars?: Record<string, unknown>) => string;

/** Label lookup for server components: `labels` prop → English. */
export function site2Text(labels: Site2BlockLabels | Record<string, unknown> | undefined, locale = "en-US"): Site2Text {
  const merged: Record<string, string> = { ...blockLabels, ...site2Labels };
  if (labels) for (const [k, v] of Object.entries(labels)) if (typeof v === "string") merged[k] = v;
  return (key, vars) => formatMessage(merged[key] ?? String(key), vars, locale);
}

/**
 * The raw (unformatted) templates for some keys, with overrides applied — plain strings that can
 * cross the RSC boundary into a client island, which formats them with `formatMessage`.
 */
export function labelTemplates<K extends Site2Key>(labels: Site2BlockLabels | Record<string, unknown> | undefined, keys: readonly K[]): Record<K, string> {
  const base: Record<string, string> = { ...blockLabels, ...site2Labels };
  const out = {} as Record<K, string>;
  for (const k of keys) {
    const v = labels ? (labels as Record<string, unknown>)[k] : undefined;
    out[k] = typeof v === "string" ? v : (base[k] ?? String(k));
  }
  return out;
}
