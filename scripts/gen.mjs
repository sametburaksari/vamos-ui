#!/usr/bin/env node
/**
 * Regenerates every shared index from the file system, so parallel work never
 * edits the same file:
 *   packages/ui/src/index.ts              ← lib/public.ts + every src/components/*.tsx
 *   apps/www/src/docs/entries/index.ts    ← every apps/www/src/docs/entries/<slug>.tsx
 *   apps/www/src/blocks/index.ts          ← every apps/www/src/blocks/<name>/meta.ts
 * Safe to run any number of times. Run: node scripts/gen.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const write = (file, content) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev !== content) {
    const tmp = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, file); // atomic: concurrent runs never leave a half-written file
  }
};
const header = "// AUTO-GENERATED by scripts/gen.mjs — do not edit by hand.\n";
const ident = (s) => s.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()).replace(/^[^a-zA-Z_]+/, "_");

// 1. UI barrel
{
  const dir = path.join(root, "packages/ui/src/components");
  const files = fs.readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && !/\.(test|stories)\./.test(f) && !f.startsWith("_")).sort();
  let out = header + 'export * from "./lib/public";\n';
  for (const f of files) out += `export * from "./components/${f.replace(/\.tsx?$/, "")}";\n`;
  write(path.join(root, "packages/ui/src/index.ts"), out);
}

// 2. Docs entries
{
  const dir = path.join(root, "apps/www/src/docs/entries");
  fs.mkdirSync(dir, { recursive: true });
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".tsx") && f !== "index.tsx").sort();
  let out = header + 'import type { DocEntry } from "../types";\n';
  for (const f of files) out += `import ${ident("doc-" + f.replace(".tsx", ""))} from "./${f.replace(".tsx", "")}";\n`;
  out += `\nexport const entries: DocEntry[] = [\n${files.map((f) => `  ${ident("doc-" + f.replace(".tsx", ""))},`).join("\n")}\n];\n`;
  write(path.join(dir, "index.ts"), out);
}

// 3. Blocks ("_shared" and other "_" folders hold fixtures, not blocks)
{
  const dir = path.join(root, "apps/www/src/blocks");
  const names = fs.readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith("_") && fs.existsSync(path.join(dir, d.name, "meta.ts"))).map((d) => d.name).sort();
  let out = header + 'import type { BlockEntry } from "./types";\n';
  for (const n of names) out += `import ${ident("meta-" + n)} from "./${n}/meta";\nimport ${ident("page-" + n)} from "./${n}/page";\n`;
  out += `\nexport const blocks: BlockEntry[] = [\n${names.map((n) => `  { ...${ident("meta-" + n)}, name: "${n}", Component: ${ident("page-" + n)} },`).join("\n")}\n].sort((a, b) => (a.order ?? 100) - (b.order ?? 100) || a.name.localeCompare(b.name));\n\nexport const blocksByName = Object.fromEntries(blocks.map((b) => [b.name, b]));\n`;
  write(path.join(dir, "index.ts"), out);
}
console.log("gen: ok");
