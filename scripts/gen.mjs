#!/usr/bin/env node
/**
 * Regenerates every shared index from the file system, so parallel work never
 * edits the same file:
 *   packages/ui/src/index.ts              ← lib/public.ts + every src/components/*.tsx
 *   apps/www/src/docs/entries/index.ts    ← every apps/www/src/docs/entries/<slug>.tsx
 *   apps/www/src/blocks/index.ts          ← every apps/www/src/blocks/<name>/meta.ts
 *   apps/www/src/app/view/<name>/page.tsx ← one preview route per block (git-ignored)
 * Safe to run any number of times. Run: node scripts/gen.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const write = (file, content) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev !== content) {
    const tmp = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, file); // atomic: concurrent runs never leave a half-written file
  }
};
const header = "// AUTO-GENERATED by scripts/gen.mjs — do not edit by hand.\n";
const ident = (s) => s.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()).replace(/^[^a-zA-Z_]+/, "_");

// 1. UI barrel — named re-exports, never `export *`: a server component that imports one name
//    from a barrel of `export *` lines makes Next (Turbopack) ship every "use client" module the
//    barrel reaches. Named lines let it keep only what is imported. Names come from the TS checker.
{
  const dir = path.join(root, "packages/ui/src/components");
  const files = fs.readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && !/\.(test|stories)\./.test(f) && !f.startsWith("_")).sort();
  // lib/public stays `export *`: it is itself all named re-exports (safe for Turbopack), and the CLI
  // inlines it into a project's index by that exact line.
  const specs = files.map((f) => `./components/${f.replace(/\.tsx?$/, "")}`);
  const ui = path.join(root, "packages/ui");
  const { namedReExports } = await import(pathToFileURL(path.join(ui, "scripts/named-exports.mjs")).href);
  write(path.join(ui, "src/index.ts"), header + 'export * from "./lib/public";\n' + namedReExports(path.join(ui, "src"), specs, ["./lib/public"]));
}

// 2. Docs entries
{
  const dir = path.join(root, "apps/www/src/docs/entries");
  fs.mkdirSync(dir, { recursive: true });
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".tsx") && f !== "index.tsx").sort();
  let out = header + 'import type { DocEntry } from "../types";\n';
  for (const f of files) out += `import ${ident("doc-" + f.replace(".tsx", ""))} from "./${f.replace(".tsx", "")}";\n`;
  out += `\nexport const entries: DocEntry[] = [\n${files.map((f) => `  ${ident("doc-" + f.replace(".tsx", ""))},`).join("\n")}\n];\n`;
  write(path.join(dir, "index.ts"), out);

  // 2b. slug + covers of every entry as plain data, for lib/catalog. Importing `entries` there
  //     pulled every docs example (editor, charts…) into the home page's client graph — and Next
  //     merges the home page's client manifest into every page, so all of it shipped everywhere.
  const covers = files.map((f) => {
    const code = fs.readFileSync(path.join(dir, f), "utf8");
    const slug = code.match(/^\s*slug:\s*"([^"]+)"/m)?.[1];
    const list = code.match(/^\s*covers:\s*(\[[^\]\n]*\])/m)?.[1];
    if (!slug || !list) throw new Error(`gen: ${f} needs a one-line \`slug: "…"\` and \`covers: ["…"]\``);
    return { slug, covers: JSON.parse(list.replace(/,\s*\]$/, "]")) };
  });
  write(
    path.join(root, "apps/www/src/docs/covers.ts"),
    header + `// Data only (no React): which inventory names each docs entry covers.\nexport const docCovers: { slug: string; covers: string[] }[] = [\n${covers.map((c) => `  ${JSON.stringify(c)},`).join("\n")}\n];\n`,
  );
}

// 3. Blocks ("_shared" and other "_" folders hold fixtures, not blocks)
{
  const dir = path.join(root, "apps/www/src/blocks");
  const names = fs.readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith("_") && fs.existsSync(path.join(dir, d.name, "meta.ts"))).map((d) => d.name).sort();
  let out = header + 'import type { BlockEntry } from "./types";\n';
  // Pages load lazily: a static import of every page would put all blocks in one client bundle.
  for (const n of names) out += `import ${ident("meta-" + n)} from "./${n}/meta";\n`;
  out += `\nexport const blocks: BlockEntry[] = [\n${names.map((n) => `  { ...${ident("meta-" + n)}, name: "${n}", load: () => import("./${n}/page") },`).join("\n")}\n].sort((a, b) => (a.order ?? 100) - (b.order ?? 100) || a.name.localeCompare(b.name));\n\nexport const blocksByName = Object.fromEntries(blocks.map((b) => [b.name, b]));\n`;
  write(path.join(dir, "index.ts"), out);

  // 4. One static route per block (/view/<name>): a shared [name] route would put every block's
  //    client code on every preview page. These files are generated and git-ignored.
  const viewDir = path.join(root, "apps/www/src/app/view");
  fs.mkdirSync(viewDir, { recursive: true });
  for (const d of fs.readdirSync(viewDir, { withFileTypes: true })) {
    const f = path.join(viewDir, d.name, "page.tsx");
    if (d.isDirectory() && !names.includes(d.name) && fs.existsSync(f) && fs.readFileSync(f, "utf8").startsWith(header)) fs.rmSync(path.join(viewDir, d.name), { recursive: true });
  }
  for (const n of names) {
    fs.mkdirSync(path.join(viewDir, n), { recursive: true });
    write(
      path.join(viewDir, n, "page.tsx"),
      header +
        `import Block from "@/blocks/${n}/page";\nimport meta from "@/blocks/${n}/meta";\nimport { pageMeta } from "@/lib/seo";\n\n` +
        `// Fictional demo content: kept out of search results; /blocks and /websites are the indexable entries.\n` +
        `export const metadata = pageMeta({ title: meta.title, description: meta.description, path: "/view/${n}/", noindex: true });\n\n` +
        `export default function View() {\n  return <Block />;\n}\n`,
    );
  }
}
console.log("gen: ok");
