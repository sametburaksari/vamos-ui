import { chromium } from "@playwright/test";
const [url, dark] = [process.argv[2], process.argv[3] === "1"];
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1440, height: 1100 } });
await ctx.addInitScript((s) => { localStorage.setItem("vamos-theme", JSON.stringify(s)); }, { dark, material: "glass", accent: "lime", density: "comfortable", font: "editorial" });
const p = await ctx.newPage();
p.on("pageerror", e => console.log("pageerror", e.message.slice(0, 300)));
p.on("console", m => { if (m.type() === "error") console.log("console", m.text().slice(0, 300)); });
const t0 = Date.now();
await p.goto("http://localhost:3200" + url, { waitUntil: "domcontentloaded", timeout: 120000 }); console.log("dcl", Date.now() - t0);
await p.waitForTimeout(4000);
const r = await Promise.race([p.evaluate(() => document.querySelectorAll(".preview-stage").length), new Promise(r => setTimeout(() => r("EVAL HANG"), 15000))]);
console.log("stages", r);
await b.close();
