// NO:17 — kişisel veriyi (üye roster'ı, prefill, bağış/katılım kayıtları) env'den
// üretir. Bu veriler repoya GİRMEZ; gitignore'lu iki dosyaya yazılır:
//   src/lib/no17-roster.generated.ts   (client: isim/doğum günü/kan grubu, TC/telefon BOŞ)
//   src/data/no17-records.json         (bağış kampanyaları + katkılar + katılım)
// Kaynak: NO17_PRIVATE_B64 (base64 JSON {members, prefill, records}).
// Vercel'de ortam değişkeninden; yerelde .env.local'dan okunur. Env yoksa boş stub yazılır.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const APP = resolve(__dirname, "..");
const ROSTER_TS = resolve(APP, "src/lib/no17-roster.generated.ts");
const RECORDS_JSON = resolve(APP, "src/data/no17-records.json");
const TICKETS_JSON = resolve(APP, "src/data/no17-tickets.generated.json");

function readEnvB64() {
  if (process.env.NO17_PRIVATE_B64) return process.env.NO17_PRIVATE_B64.trim();
  // Yerel geliştirme: .env.local'dan çek (node otomatik yüklemez).
  const envLocal = resolve(APP, ".env.local");
  if (existsSync(envLocal)) {
    const m = readFileSync(envLocal, "utf8").match(/^NO17_PRIVATE_B64=(.+)$/m);
    if (m) return m[1].trim();
  }
  return null;
}

const EMPTY = { members: [], prefill: {}, records: { campaigns: [], contrib: {}, attendance: {} }, tickets: [] };

let data = EMPTY;
const b64 = readEnvB64();
if (b64) {
  try {
    const parsed = JSON.parse(Buffer.from(b64, "base64").toString("utf8"));
    data = {
      members: Array.isArray(parsed.members) ? parsed.members : [],
      prefill: parsed.prefill ?? {},
      records: parsed.records ?? EMPTY.records,
      tickets: Array.isArray(parsed.tickets) ? parsed.tickets : [],
    };
  } catch (e) {
    console.warn("[gen-no17-private] NO17_PRIVATE_B64 çözülemedi, boş stub yazılıyor:", e.message);
  }
} else {
  console.warn("[gen-no17-private] NO17_PRIVATE_B64 yok — boş stub yazılıyor (demo/CI).");
}

// Client roster'da TC/telefon asla bulunmasın (güvenlik).
const members = data.members.map((m) => ({ ...m, tc: "", phone: "" }));

const roster = `// AUTO-GENERATED by scripts/gen-no17-private.mjs — DÜZENLEME, COMMIT ETME.
// Kaynak: NO17_PRIVATE_B64 env. Kişisel veri; .gitignore'da.
import type { Member } from "./no17-data";
export const MEMBERS: Member[] = ${JSON.stringify(members, null, 2)};
export const PREFILL: Record<string, string[]> = ${JSON.stringify(data.prefill, null, 2)};
`;

writeFileSync(ROSTER_TS, roster);
writeFileSync(RECORDS_JSON, JSON.stringify(data.records, null, 2) + "\n");
writeFileSync(TICKETS_JSON, JSON.stringify(data.tickets ?? [], null, 2) + "\n");
console.log(`[gen-no17-private] yazıldı: ${members.length} üye, ${Object.keys(data.prefill).length} prefill, ${data.records.campaigns?.length ?? 0} kampanya, ${(data.tickets ?? []).length} bilet`);
